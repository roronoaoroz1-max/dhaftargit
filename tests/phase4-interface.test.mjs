import assert from "node:assert/strict";
import vm from "node:vm";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const html=read("stock.html"),source=read("stock-planning.js");
const ctx=vm.createContext({});vm.runInContext(source,ctx);
const p=ctx.StockPlanning;
assert.equal(p.validDecimal("1.234",3,true),1.234);
assert.equal(p.validDecimal("1.2345",3,true),null);
assert.equal(p.validDecimal("0",2,false),0);
assert.equal(p.validDecimal("",2,false),null);
assert.equal(p.forecast({manualLow:false},{daysLeft:8},7),null);
assert.equal(p.forecast({manualLow:true},{daysLeft:null,latest:{qty:2},avgUnitPrice:125},7).cost,250);
assert.equal(p.forecast({manualLow:true},{daysLeft:null,avgUnitPrice:null},7).cost,null);
const ids=new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]));
for(const m of source.matchAll(/\bel\("([^"]+)"\)/g))assert.ok(ids.has(m[1]),"Missing ID "+m[1]);
for(const m of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi))if(m[1].trim())new vm.Script(m[1]);
assert.ok(html.includes('StockPlanning.bind('));
console.log("PASS: forecast calculations, decimal validation, HTML integration and syntax");
